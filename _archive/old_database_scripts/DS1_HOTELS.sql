-- ============================================================================
-- PART 1: CREATE SCHEMA FOR DS_1
-- ============================================================================

-- Create tablespace (if not exists)
BEGIN
    EXECUTE IMMEDIATE 'CREATE TABLESPACE DS1_HOTELS_DATA
        DATAFILE ''/data/ds1_hotels_data01.dbf'' SIZE 100M
        AUTOEXTEND ON';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -1543 THEN RAISE; END IF;
END;
/

-- Create user for DS_1 data source
BEGIN
    EXECUTE IMMEDIATE 'DROP USER DS1_HOTELS CASCADE';
EXCEPTION
    WHEN OTHERS THEN NULL;
END;
/

CREATE USER DS1_HOTELS IDENTIFIED BY Ds1Hotels2025!
    DEFAULT TABLESPACE DS1_HOTELS_DATA
    QUOTA UNLIMITED ON DS1_HOTELS_DATA;

GRANT CREATE SESSION, CREATE TABLE TO DS1_HOTELS;

PROMPT [DS_1] User DS1_HOTELS created

-- ============================================================================
-- PART 2: TABLE 1 - HOTELS (8 records)
-- ============================================================================

CREATE TABLE DS1_HOTELS.HOTELS (
    HOTEL_ID          NUMBER(4) PRIMARY KEY,
    HOTEL_NAME        VARCHAR2(100) NOT NULL,
    CITY              VARCHAR2(50) NOT NULL,
    COUNTRY           VARCHAR2(50) NOT NULL,
    STAR_RATING       NUMBER(1) CHECK (STAR_RATING BETWEEN 1 AND 5),
    ROOMS_TOTAL       NUMBER(4) NOT NULL,
    PRICE_PER_NIGHT   NUMBER(8,2),
    POOL              CHAR(1) DEFAULT 'Y',
    WIFI              CHAR(1) DEFAULT 'Y',
    CREATED_DATE      DATE DEFAULT SYSDATE
)
TABLESPACE DS1_HOTELS_DATA;

COMMENT ON TABLE DS1_HOTELS.HOTELS IS 'Hotel properties and basic information';
COMMENT ON COLUMN DS1_HOTELS.HOTELS.HOTEL_ID IS 'Unique hotel identifier';
COMMENT ON COLUMN DS1_HOTELS.HOTELS.STAR_RATING IS 'Hotel classification 1-5 stars';
COMMENT ON COLUMN DS1_HOTELS.HOTELS.PRICE_PER_NIGHT IS 'Average nightly rate in EUR';

PROMPT [DS_1] Table HOTELS created

-- ============================================================================
-- PART 3: TABLE 2 - ROOM_TYPES (24 records)
-- ============================================================================

CREATE TABLE DS1_HOTELS.ROOM_TYPES (
    ROOM_TYPE_ID      NUMBER(4) PRIMARY KEY,
    HOTEL_ID          NUMBER(4) NOT NULL REFERENCES DS1_HOTELS.HOTELS(HOTEL_ID),
    ROOM_TYPE_NAME    VARCHAR2(50) NOT NULL,
    CAPACITY          NUMBER(2) NOT NULL,
    BASE_PRICE        NUMBER(8,2) NOT NULL,
    TAX_RATE          NUMBER(3,2) DEFAULT 21.00,
    AVAILABILITY      CHAR(1) DEFAULT 'Y'
)
TABLESPACE DS1_HOTELS_DATA;

CREATE INDEX IDX_RT_HOTEL ON DS1_HOTELS.ROOM_TYPES(HOTEL_ID);

COMMENT ON TABLE DS1_HOTELS.ROOM_TYPES IS 'Room categories and pricing tiers';
COMMENT ON COLUMN DS1_HOTELS.ROOM_TYPES.CAPACITY IS 'Maximum number of guests';
COMMENT ON COLUMN DS1_HOTELS.ROOM_TYPES.TAX_RATE IS 'VAT percentage';

PROMPT [DS_1] Table ROOM_TYPES created

-- ============================================================================
-- PART 4: TABLE 3 - BOOKINGS_HISTORY (120 records)
-- ============================================================================

CREATE TABLE DS1_HOTELS.BOOKINGS_HISTORY (
    BOOKING_ID        NUMBER(6) PRIMARY KEY,
    HOTEL_ID          NUMBER(4) NOT NULL REFERENCES DS1_HOTELS.HOTELS(HOTEL_ID),
    ROOM_TYPE_ID      NUMBER(4) NOT NULL REFERENCES DS1_HOTELS.ROOM_TYPES(ROOM_TYPE_ID),
    CHECK_IN_DATE     DATE NOT NULL,
    CHECK_OUT_DATE    DATE NOT NULL,
    NIGHTS            NUMBER(3) NOT NULL,
    GUEST_COUNT       NUMBER(2) NOT NULL,
    BOOKING_DATE      DATE DEFAULT SYSDATE,
    TOTAL_PRICE       NUMBER(10,2) NOT NULL,
    STATUS            VARCHAR2(20) DEFAULT 'Confirmed'
)
TABLESPACE DS1_HOTELS_DATA;

CREATE INDEX IDX_BH_HOTEL ON DS1_HOTELS.BOOKINGS_HISTORY(HOTEL_ID);
CREATE INDEX IDX_BH_DATES ON DS1_HOTELS.BOOKINGS_HISTORY(CHECK_IN_DATE, CHECK_OUT_DATE);

COMMENT ON TABLE DS1_HOTELS.BOOKINGS_HISTORY IS 'Historical booking data';
COMMENT ON COLUMN DS1_HOTELS.BOOKINGS_HISTORY.NIGHTS IS 'Length of stay in nights';
COMMENT ON COLUMN DS1_HOTELS.BOOKINGS_HISTORY.TOTAL_PRICE IS 'Total price including taxes in EUR';

PROMPT [DS_1] Table BOOKINGS_HISTORY created

