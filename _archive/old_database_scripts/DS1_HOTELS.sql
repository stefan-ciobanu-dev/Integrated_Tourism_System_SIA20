CREATE OR REPLACE VIEW DS1_HOTELS.V_BOOKINGS_SUMMARY AS
SELECT
    H.HOTEL_NAME,
    H.CITY,
    COUNT(B.BOOKING_ID) AS TOTAL_BOOKINGS,
    COUNT(CASE WHEN B.STATUS='Confirmed' THEN 1 END) AS CONFIRMED,
    COUNT(CASE WHEN B.STATUS='Cancelled' THEN 1 END) AS CANCELLED,
    SUM(B.TOTAL_PRICE) AS TOTAL_REVENUE,
    AVG(B.NIGHTS) AS AVG_STAY_DURATION,
    MAX(B.BOOKING_DATE) AS LAST_BOOKING
FROM DS1_HOTELS.HOTELS H
LEFT JOIN DS1_HOTELS.BOOKINGS_HISTORY B ON H.HOTEL_ID = B.HOTEL_ID
GROUP BY H.HOTEL_ID, H.HOTEL_NAME, H.CITY
ORDER BY TOTAL_REVENUE DESC;

