CREATE TABLE REGIONS (
    REGION_ID NUMBER PRIMARY KEY,
    REGION_NAME VARCHAR2(100) NOT NULL,
    REGION_CODE VARCHAR2(10),
    POPULATION NUMBER,
    GDP DECIMAL(18,2),
    CREATED_DATE TIMESTAMP DEFAULT SYSDATE
);

CREATE TABLE DESTINATIONS (
    DESTINATION_ID NUMBER PRIMARY KEY,
    REGION_ID NUMBER REFERENCES REGIONS(REGION_ID),
    NAME VARCHAR2(200) NOT NULL,
    TYPE VARCHAR2(50),
    LATITUDE DECIMAL(10,8),
    LONGITUDE DECIMAL(11,8),
    VISITORS_ANNUAL NUMBER,
    CREATED_DATE TIMESTAMP DEFAULT SYSDATE
);

CREATE TABLE HOTELS (
    HOTEL_ID NUMBER PRIMARY KEY,
    DESTINATION_ID NUMBER REFERENCES DESTINATIONS(DESTINATION_ID),
    NAME VARCHAR2(200) NOT NULL,
    STARS NUMBER,
    ROOMS_TOTAL NUMBER,
    ROOMS_AVAILABLE NUMBER,
    PRICE_PER_NIGHT DECIMAL(10,2),
    CREATED_DATE TIMESTAMP DEFAULT SYSDATE
);

CREATE TABLE BOOKINGS (
    BOOKING_ID NUMBER PRIMARY KEY,
    HOTEL_ID NUMBER REFERENCES HOTELS(HOTEL_ID),
    BOOKING_DATE TIMESTAMP,
    CHECK_IN_DATE DATE,
    CHECK_OUT_DATE DATE,
    GUEST_NAME VARCHAR2(200),
    TOTAL_COST DECIMAL(12,2),
    STATUS VARCHAR2(50),
    CREATED_DATE TIMESTAMP DEFAULT SYSDATE
);

CREATE TABLE FLIGHTS (
    FLIGHT_ID NUMBER PRIMARY KEY,
    AIRLINE_CODE VARCHAR2(10),
    FLIGHT_NUMBER VARCHAR2(20),
    ORIGIN_AIRPORT VARCHAR2(10),
    DESTINATION_AIRPORT VARCHAR2(10),
    DEPARTURE_TIME TIMESTAMP,
    ARRIVAL_TIME TIMESTAMP,
    AIRCRAFT_TYPE VARCHAR2(50),
    PASSENGERS_COUNT NUMBER,
    CREATED_DATE TIMESTAMP DEFAULT SYSDATE
);

-- ============================================================================
