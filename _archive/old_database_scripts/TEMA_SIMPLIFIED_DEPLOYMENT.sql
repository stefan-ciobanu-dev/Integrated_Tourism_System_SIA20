-- PART 4: CREATE VIEWS FOR ANALYTICS
-- ============================================================================

-- View: Hotels by destination with average rating
CREATE VIEW V_HOTELS_BY_DESTINATION AS
SELECT 
    d.DESTINATION_ID,
    d.NAME AS DESTINATION_NAME,
    d.VISITORS_ANNUAL,
    COUNT(h.HOTEL_ID) AS HOTEL_COUNT,
    AVG(h.STARS) AS AVG_STARS,
    AVG(h.PRICE_PER_NIGHT) AS AVG_PRICE
FROM DESTINATIONS d
LEFT JOIN HOTELS h ON d.DESTINATION_ID = h.DESTINATION_ID
GROUP BY d.DESTINATION_ID, d.NAME, d.VISITORS_ANNUAL;

-- View: Bookings summary by hotel
CREATE VIEW V_BOOKINGS_BY_HOTEL AS
SELECT
    h.HOTEL_ID,
    h.NAME AS HOTEL_NAME,
    d.NAME AS DESTINATION_NAME,
    COUNT(b.BOOKING_ID) AS TOTAL_BOOKINGS,
    SUM(b.TOTAL_COST) AS TOTAL_REVENUE,
    AVG(b.TOTAL_COST) AS AVG_BOOKING_VALUE
FROM HOTELS h
LEFT JOIN DESTINATIONS d ON h.DESTINATION_ID = d.DESTINATION_ID
LEFT JOIN BOOKINGS b ON h.HOTEL_ID = b.HOTEL_ID AND b.STATUS = 'CONFIRMED'
GROUP BY h.HOTEL_ID, h.NAME, d.NAME;

-- View: Tourism statistics by region
CREATE VIEW V_TOURISM_BY_REGION AS
SELECT
    r.REGION_ID,
    r.REGION_NAME,
    COUNT(DISTINCT d.DESTINATION_ID) AS DESTINATIONS,
    COUNT(DISTINCT h.HOTEL_ID) AS HOTELS,
    SUM(h.ROOMS_TOTAL) AS TOTAL_ROOMS,
    AVG(d.VISITORS_ANNUAL) AS AVG_VISITORS
FROM REGIONS r
LEFT JOIN DESTINATIONS d ON r.REGION_ID = d.REGION_ID
LEFT JOIN HOTELS h ON d.DESTINATION_ID = h.DESTINATION_ID
GROUP BY r.REGION_ID, r.REGION_NAME;

