PROMPT [4] Creating Federation Views (Unified Access Layer)...

CREATE OR REPLACE VIEW TOURISM_ADMIN.V_DS1_HOTELS AS
SELECT 
  HOTEL_ID,
  HOTEL_NAME,
  CITY,
  COUNTRY,
  STAR_RATING,
  TOTAL_ROOMS,
  YEAR_OPENED,
  'DS_1_HOTELS' as SOURCE_SYSTEM,
  'DIRECT_TABLE' as ACCESS_MECHANISM
FROM TOURISM_ADMIN.HOTELS_DS1;

CREATE OR REPLACE VIEW TOURISM_ADMIN.V_DS1_ROOMS AS
SELECT 
  r.ROOM_TYPE_ID,
  h.HOTEL_ID,
  h.HOTEL_NAME,
  r.ROOM_TYPE,
  r.CAPACITY,
  r.NIGHTLY_RATE,
  r.AVAILABLE_ROOMS,
  r.CURRENCY,
  'DS_1_HOTELS' as SOURCE_SYSTEM,
  'DIRECT_TABLE' as ACCESS_MECHANISM
FROM TOURISM_ADMIN.HOTELS_DS1 h
INNER JOIN TOURISM_ADMIN.ROOM_TYPES_DS1 r ON h.HOTEL_ID = r.HOTEL_ID;

CREATE OR REPLACE VIEW TOURISM_ADMIN.V_DS1_BOOKINGS AS
SELECT 
  b.BOOKING_ID,
  h.HOTEL_ID,
  h.HOTEL_NAME,
  b.GUEST_NAME,
  b.CHECK_IN_DATE,
  b.CHECK_OUT_DATE,
  b.NIGHTS,
  b.TOTAL_PRICE,
  b.BOOKING_STATUS,
  'DS_1_HOTELS' as SOURCE_SYSTEM,
  'DIRECT_TABLE' as ACCESS_MECHANISM
FROM TOURISM_ADMIN.HOTELS_DS1 h
INNER JOIN TOURISM_ADMIN.BOOKINGS_DS1 b ON h.HOTEL_ID = b.HOTEL_ID;

CREATE OR REPLACE VIEW TOURISM_ADMIN.V_DS2_FLIGHTS AS
SELECT 
  FLIGHT_ID,
  ICAO24,
  CALLSIGN,
  ORIGIN_COUNTRY,
  ORIGIN_AIRPORT,
  DESTINATION_AIRPORT,
  LATITUDE,
  LONGITUDE,
  ALTITUDE_M,
  VELOCITY_MS,
  CAPTURE_TIME,
  'DS_2_OPENSKY' as SOURCE_SYSTEM,
  'REST_API' as ACCESS_MECHANISM
FROM TOURISM_ADMIN.FLIGHTS_DS2_CACHE;

CREATE OR REPLACE VIEW TOURISM_ADMIN.V_DS3_CURRENCIES AS
SELECT 
  CURRENCY_CODE,
  CURRENCY_NAME,
  EUR_RATE,
  RATE_DATE,
  SOURCE,
  LAST_UPDATE,
  'DS_3_ECB' as SOURCE_SYSTEM,
  'HTTP_XML' as ACCESS_MECHANISM
FROM TOURISM_ADMIN.CURRENCY_DS3;

COMMIT;

