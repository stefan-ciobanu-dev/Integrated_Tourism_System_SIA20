CREATE TABLE IF NOT EXISTS TOURISM_ADMIN.HOTELS_DS1 (
  HOTEL_ID NUMBER PRIMARY KEY,
  HOTEL_NAME VARCHAR2(200),
  CITY VARCHAR2(100),
  COUNTRY VARCHAR2(50),
  STAR_RATING NUMBER(2,1),
  TOTAL_ROOMS NUMBER,
  YEAR_OPENED NUMBER(4)
) TABLESPACE USERS;

CREATE TABLE IF NOT EXISTS TOURISM_ADMIN.ROOM_TYPES_DS1 (
  ROOM_TYPE_ID NUMBER PRIMARY KEY,
  HOTEL_ID NUMBER REFERENCES TOURISM_ADMIN.HOTELS_DS1(HOTEL_ID),
  ROOM_TYPE VARCHAR2(50),
  CAPACITY NUMBER,
  NIGHTLY_RATE DECIMAL(10,2),
  AVAILABLE_ROOMS NUMBER,
  CURRENCY VARCHAR2(3)
) TABLESPACE USERS;

CREATE TABLE IF NOT EXISTS TOURISM_ADMIN.BOOKINGS_DS1 (
  BOOKING_ID VARCHAR2(20) PRIMARY KEY,
  HOTEL_ID NUMBER REFERENCES TOURISM_ADMIN.HOTELS_DS1(HOTEL_ID),
  GUEST_NAME VARCHAR2(100),
  CHECK_IN_DATE DATE,
  CHECK_OUT_DATE DATE,
  NIGHTS NUMBER,
  ROOM_TYPE VARCHAR2(50),
  TOTAL_PRICE DECIMAL(12,2),
  BOOKING_STATUS VARCHAR2(20)
) TABLESPACE USERS;

