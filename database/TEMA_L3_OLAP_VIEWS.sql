-- Consolidation View 1: Booking with Guest and Hotel Information
CREATE OR REPLACE VIEW TOURISM_ADMIN.V_CONSOLIDATE_BOOKINGS AS
SELECT 
  b.BOOKING_ID,
  b.GUEST_NAME,
  h.HOTEL_ID,
  h.HOTEL_NAME,
  h.CITY,
  h.COUNTRY,
  h.STAR_RATING,
  b.CHECK_IN_DATE,
  b.CHECK_OUT_DATE,
  b.NIGHTS,
  r.ROOM_TYPE,
  r.CAPACITY,
  r.NIGHTLY_RATE,
  r.CURRENCY,
  b.TOTAL_PRICE,
  b.BOOKING_STATUS,
  'BOOKING_MASTER' as RECORD_TYPE
FROM 
  TOURISM_ADMIN.V_DS1_BOOKINGS b
  INNER JOIN TOURISM_ADMIN.V_DS1_HOTELS h ON b.HOTEL_ID = h.HOTEL_ID
  LEFT JOIN TOURISM_ADMIN.V_DS1_ROOMS r ON b.ROOM_TYPE = r.ROOM_TYPE AND h.HOTEL_ID = r.HOTEL_ID;

-- Consolidation View 2: Accommodation Inventory with Multi-Currency Support
CREATE OR REPLACE VIEW TOURISM_ADMIN.V_CONSOLIDATE_ACCOMMODATION AS
SELECT 
  h.HOTEL_ID,
  h.HOTEL_NAME,
  h.CITY,
  h.COUNTRY,
  h.STAR_RATING,
  h.TOTAL_ROOMS,
  h.YEAR_OPENED,
  r.ROOM_TYPE_ID,
  r.ROOM_TYPE,
  r.CAPACITY,
  r.NIGHTLY_RATE,
  r.CURRENCY,
  c.EUR_RATE,
  ROUND(r.NIGHTLY_RATE / NULLIF(c.EUR_RATE, 0), 2) as NIGHTLY_RATE_EUR,
  r.AVAILABLE_ROOMS
FROM 
  TOURISM_ADMIN.V_DS1_HOTELS h
  INNER JOIN TOURISM_ADMIN.V_DS1_ROOMS r ON h.HOTEL_ID = r.HOTEL_ID
  LEFT JOIN TOURISM_ADMIN.V_DS3_CURRENCIES c ON r.CURRENCY = c.CURRENCY_CODE
WHERE 
  c.CURRENCY_CODE IS NOT NULL;

-- Consolidation View 3: Travel Integration (Bookings + Flights)
CREATE OR REPLACE VIEW TOURISM_ADMIN.V_CONSOLIDATE_TRAVEL AS
SELECT 
  b.BOOKING_ID,
  b.GUEST_NAME,
  h.HOTEL_NAME,
  h.CITY,
  b.CHECK_IN_DATE,
  b.CHECK_OUT_DATE,
  b.NIGHTS,
  f.CALLSIGN,
  f.ORIGIN_AIRPORT,
  f.DESTINATION_AIRPORT,
  f.ORIGIN_COUNTRY,
  f.ALTITUDE_M,
  b.TOTAL_PRICE,
  b.BOOKING_STATUS
FROM 
  TOURISM_ADMIN.V_DS1_BOOKINGS b
  INNER JOIN TOURISM_ADMIN.V_DS1_HOTELS h ON b.HOTEL_ID = h.HOTEL_ID
  CROSS JOIN TOURISM_ADMIN.V_DS2_FLIGHTS f;

