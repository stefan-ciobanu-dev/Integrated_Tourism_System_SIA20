-- OLAP View 1: Booking Revenue Analysis by Hotel (ROLLUP)
CREATE OR REPLACE VIEW TOURISM_ADMIN.V_ANALYTICS_REVENUE_ROLLUP AS
SELECT 
  GROUPING_ID(d.HOTEL_NAME, d.STAR_RATING, d.ROOM_TYPE) as GROUPING_LEVEL,
  CASE 
    WHEN GROUPING(d.HOTEL_NAME) = 1 THEN 'ALL_HOTELS'
    ELSE d.HOTEL_NAME
  END as HOTEL_NAME,
  CASE 
    WHEN GROUPING(d.STAR_RATING) = 1 THEN NULL
    ELSE d.STAR_RATING
  END as STAR_RATING,
  CASE 
    WHEN GROUPING(d.ROOM_TYPE) = 1 THEN 'ALL_ROOMS'
    ELSE d.ROOM_TYPE
  END as ROOM_TYPE,
  COUNT(*) as BOOKING_COUNT,
  SUM(fb.TOTAL_AMOUNT_LOCAL) as TOTAL_REVENUE_LOCAL,
  SUM(fb.TOTAL_AMOUNT_EUR) as TOTAL_REVENUE_EUR,
  ROUND(AVG(fb.TOTAL_AMOUNT_EUR), 2) as AVG_BOOKING_VALUE_EUR,
  SUM(fb.NIGHTS_COUNT) as TOTAL_NIGHTS
FROM 
  TOURISM_ADMIN.FACT_BOOKINGS fb
  INNER JOIN TOURISM_ADMIN.DIM_ACCOMMODATION d ON fb.ACCOMMODATION_ID = d.ACCOMMODATION_ID
GROUP BY ROLLUP (d.HOTEL_NAME, d.STAR_RATING, d.ROOM_TYPE);

-- OLAP View 2: Revenue Analysis by Location and Currency (CUBE)
CREATE OR REPLACE VIEW TOURISM_ADMIN.V_ANALYTICS_LOCATION_CUBE AS
SELECT 
  GROUPING_ID(c.COUNTRY, c.CITY, cur.CURRENCY_CODE) as GROUPING_LEVEL,
  CASE 
    WHEN GROUPING(c.COUNTRY) = 1 THEN 'TOTAL'
    ELSE c.COUNTRY
  END as COUNTRY,
  CASE 
    WHEN GROUPING(c.CITY) = 1 THEN 'ALL_CITIES'
    ELSE c.CITY
  END as CITY,
  CASE 
    WHEN GROUPING(cur.CURRENCY_CODE) = 1 THEN 'MULTI_CURRENCY'
    ELSE cur.CURRENCY_CODE
  END as CURRENCY_CODE,
  COUNT(DISTINCT fb.BOOKING_ID) as BOOKINGS,
  SUM(fb.TOTAL_AMOUNT_LOCAL) as REVENUE_LOCAL,
  SUM(fb.TOTAL_AMOUNT_EUR) as REVENUE_EUR,
  ROUND(SUM(fb.TOTAL_AMOUNT_EUR) / NULLIF(COUNT(DISTINCT fb.BOOKING_ID), 0), 2) as AVG_VALUE_EUR,
  SUM(CASE WHEN fb.BOOKING_STATUS = 'CONFIRMED' THEN 1 ELSE 0 END) as CONFIRMED_BOOKINGS
FROM 
  TOURISM_ADMIN.FACT_BOOKINGS fb
  INNER JOIN TOURISM_ADMIN.DIM_ACCOMMODATION d ON fb.ACCOMMODATION_ID = d.ACCOMMODATION_ID
  INNER JOIN TOURISM_ADMIN.DIM_LOCATION c ON fb.LOCATION_ID = c.LOCATION_ID
  INNER JOIN TOURISM_ADMIN.DIM_CURRENCY cur ON fb.CURRENCY_ID = cur.CURRENCY_ID
GROUP BY CUBE (c.COUNTRY, c.CITY, cur.CURRENCY_CODE);

-- OLAP View 3: Temporal Analysis with Window Functions
CREATE OR REPLACE VIEW TOURISM_ADMIN.V_ANALYTICS_TEMPORAL_TREND AS
SELECT 
  d.FULL_DATE,
  d.MONTH_NAME,
  d.WEEK_OF_YEAR,
  COUNT(*) OVER (ORDER BY d.FULL_DATE) as CUMULATIVE_BOOKINGS,
  SUM(fb.TOTAL_AMOUNT_EUR) OVER (ORDER BY d.FULL_DATE) as CUMULATIVE_REVENUE_EUR,
  SUM(fb.TOTAL_AMOUNT_EUR) OVER (PARTITION BY d.MONTH ORDER BY d.FULL_DATE) as MONTHLY_RUNNING_TOTAL,
  ROW_NUMBER() OVER (ORDER BY fb.TOTAL_AMOUNT_EUR DESC) as REVENUE_RANK,
  DENSE_RANK() OVER (PARTITION BY d.MONTH ORDER BY fb.TOTAL_AMOUNT_EUR DESC) as MONTHLY_RANK,
  FIRST_VALUE(fb.TOTAL_AMOUNT_EUR) OVER (PARTITION BY d.MONTH ORDER BY d.FULL_DATE) as FIRST_BOOKING_VALUE_MONTH,
  LAST_VALUE(fb.TOTAL_AMOUNT_EUR) OVER (PARTITION BY d.MONTH ORDER BY d.FULL_DATE 
    ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) as LAST_BOOKING_VALUE_MONTH
FROM 
  TOURISM_ADMIN.FACT_BOOKINGS fb
  INNER JOIN TOURISM_ADMIN.DIM_DATE d ON fb.CHECK_IN_DATE_ID = d.DATE_ID
ORDER BY 
  d.FULL_DATE;

-- OLAP View 4: Occupancy Rate Analysis
CREATE OR REPLACE VIEW TOURISM_ADMIN.V_ANALYTICS_OCCUPANCY AS
SELECT 
  d.HOTEL_NAME,
  d.STAR_RATING,
  dd.FULL_DATE,
  fa.AVAILABLE_ROOMS,
  fa.OCCUPANCY_RATE,
  AVG(fa.OCCUPANCY_RATE) OVER (PARTITION BY d.HOTEL_NAME ORDER BY dd.FULL_DATE 
    ROWS BETWEEN 2 PRECEDING AND CURRENT ROW) as MOVING_AVG_OCCUPANCY_3DAY,
  LEAD(fa.OCCUPANCY_RATE) OVER (PARTITION BY d.HOTEL_NAME ORDER BY dd.FULL_DATE) as NEXT_DAY_OCCUPANCY,
  LAG(fa.OCCUPANCY_RATE) OVER (PARTITION BY d.HOTEL_NAME ORDER BY dd.FULL_DATE) as PREV_DAY_OCCUPANCY,
  MAX(fa.OCCUPANCY_RATE) OVER (PARTITION BY d.HOTEL_NAME) as MAX_OCCUPANCY,
  SUM(fa.REVENUE_POTENTIAL) OVER (PARTITION BY d.HOTEL_NAME) as TOTAL_REVENUE_POTENTIAL
FROM 
  TOURISM_ADMIN.FACT_ACCOMMODATION fa
  INNER JOIN TOURISM_ADMIN.DIM_ACCOMMODATION d ON fa.ACCOMMODATION_ID = d.ACCOMMODATION_ID
  INNER JOIN TOURISM_ADMIN.DIM_DATE dd ON fa.DATE_ID = dd.DATE_ID;

-- OLAP View 5: Top Performers Ranking
CREATE OR REPLACE VIEW TOURISM_ADMIN.V_ANALYTICS_TOP_PERFORMERS AS
SELECT 
  d.HOTEL_NAME,
  d.STAR_RATING,
  d.ROOM_TYPE,
  COUNT(*) as TOTAL_BOOKINGS,
  SUM(fb.TOTAL_AMOUNT_EUR) as TOTAL_REVENUE_EUR,
  ROUND(AVG(fb.TOTAL_AMOUNT_EUR), 2) as AVG_BOOKING_EUR,
  ROW_NUMBER() OVER (ORDER BY SUM(fb.TOTAL_AMOUNT_EUR) DESC) as REVENUE_RANK,
  ROUND(100 * SUM(fb.TOTAL_AMOUNT_EUR) / SUM(SUM(fb.TOTAL_AMOUNT_EUR)) OVER (), 2) as REVENUE_PERCENTAGE
FROM 
  TOURISM_ADMIN.FACT_BOOKINGS fb
  INNER JOIN TOURISM_ADMIN.DIM_ACCOMMODATION d ON fb.ACCOMMODATION_ID = d.ACCOMMODATION_ID
GROUP BY 
  d.HOTEL_NAME, d.STAR_RATING, d.ROOM_TYPE
ORDER BY 
  TOTAL_REVENUE_EUR DESC;

-- OLAP View 6: Multi-Dimensional Analysis
CREATE OR REPLACE VIEW TOURISM_ADMIN.V_ANALYTICS_MULTIDIM AS
SELECT 
  d.STAR_RATING,
  d.HOTEL_NAME,
  loc.CITY,
  loc.COUNTRY,
  cur.CURRENCY_CODE,
  cur.EUR_RATE,
  COUNT(*) as BOOKINGS,
  SUM(fb.TOTAL_AMOUNT_LOCAL) as REVENUE_LOCAL,
  SUM(fb.TOTAL_AMOUNT_EUR) as REVENUE_EUR,
  ROUND(SUM(fb.NIGHTS_COUNT) / COUNT(*), 1) as AVG_NIGHTS_PER_BOOKING,
  ROUND(SUM(fb.TOTAL_AMOUNT_EUR) / NULLIF(SUM(fb.NIGHTS_COUNT), 0), 2) as REVENUE_PER_NIGHT_EUR
FROM 
  TOURISM_ADMIN.FACT_BOOKINGS fb
  INNER JOIN TOURISM_ADMIN.DIM_ACCOMMODATION d ON fb.ACCOMMODATION_ID = d.ACCOMMODATION_ID
  INNER JOIN TOURISM_ADMIN.DIM_LOCATION loc ON fb.LOCATION_ID = loc.LOCATION_ID
  INNER JOIN TOURISM_ADMIN.DIM_CURRENCY cur ON fb.CURRENCY_ID = cur.CURRENCY_ID
GROUP BY 
  d.STAR_RATING, d.HOTEL_NAME, loc.CITY, loc.COUNTRY, cur.CURRENCY_CODE, cur.EUR_RATE;

-- OLAP View 7: Geographic Revenue Heatmap
CREATE OR REPLACE VIEW TOURISM_ADMIN.V_ANALYTICS_GEOGRAPHIC_HEATMAP AS
SELECT 
  loc.COUNTRY,
  loc.CITY,
  loc.LATITUDE,
  loc.LONGITUDE,
  COUNT(*) as BOOKING_COUNT,
  SUM(fb.TOTAL_AMOUNT_EUR) as TOTAL_REVENUE_EUR,
  ROUND(AVG(fb.TOTAL_AMOUNT_EUR), 2) as AVG_BOOKING_EUR,
  RANK() OVER (ORDER BY SUM(fb.TOTAL_AMOUNT_EUR) DESC) as CITY_REVENUE_RANK,
  ROUND(100 * SUM(fb.TOTAL_AMOUNT_EUR) / SUM(SUM(fb.TOTAL_AMOUNT_EUR)) OVER (), 2) as REVENUE_SHARE_PCT
FROM 
  TOURISM_ADMIN.FACT_BOOKINGS fb
  INNER JOIN TOURISM_ADMIN.DIM_LOCATION loc ON fb.LOCATION_ID = loc.LOCATION_ID
GROUP BY 
  loc.COUNTRY, loc.CITY, loc.LATITUDE, loc.LONGITUDE
ORDER BY 
  TOTAL_REVENUE_EUR DESC;

